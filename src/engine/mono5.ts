const CELL = 5;
const PER_ROW = 16;

let cached: BitmapFont | null = null;

export function buildMono5Font(): BitmapFont {
  if (cached) return cached;

  const names = Object.keys(GLYPHS);
  const rows = Math.ceil(names.length / PER_ROW);
  const texture = makeRaster(PER_ROW * CELL, rows * CELL);
  const glyphs = new Map<number, Glyph>();

  names.forEach((name, index) => {
    const sx = (index % PER_ROW) * CELL;
    const sy = Math.floor(index / PER_ROW) * CELL;
    const art = GLYPHS[name]!;

    for (let y = 0; y < CELL; y++) {
      for (let x = 0; x < CELL; x++) {
        if (art[y]![x] === "#") {
          texture.data.set([255, 255, 255, 255], ((sy + y) * texture.width + (sx + x)) * 4);
        }
      }
    }

    // width 5 for every glyph — advance 6, strictly monospace, the space included.
    const glyph: Glyph = { sx, sy, cellW: CELL, cellH: CELL, width: CELL };
    glyphs.set(name.codePointAt(0)!, glyph);

    // Lowercase letters share the uppercase art.
    if (/^[A-Z]$/.test(name)) glyphs.set(name.toLowerCase().codePointAt(0)!, glyph);
  });

  cached = { texture, glyphs, cellH: CELL };
  return cached;
}
